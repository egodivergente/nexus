"""Explicit Flow parameters for Android through the verified desktop contract.

The browser bridge (`/api/flow/jobs`) types into whatever the Flow editor currently has selected: it cannot choose the
model, aspect ratio, duration or start/end frames, and it ignored the frame ids Android sent. This module exposes the
same own-account route Nexus Desktop uses (`flow_provider` + `flow_contract`, gflow runtime on AXELPC):

* capabilities are derived from `flow_contract.normalize`, so the phone only offers combinations Flow accepts;
* every submission needs a fresh quote and the caller must echo its amount (`cost`), exactly like Desktop;
* request ids are idempotent: repeating one returns the existing job, recovery never resubmits;
* 2K/4K (image) and 1080p/4K (video) are Flow's own download processing of an existing result, quoted separately.
  There is no upscaler here and nothing is generated by asking for options.

Reference images come from the bridge's integrity-checked `flow-references/ref_<sha256>` store and are copied into the
provider's `media/<sha256[:32]>` folder, which is the only input format the desktop contract accepts.
"""
from __future__ import annotations

import asyncio
import importlib
import re
import shutil
import sys
from pathlib import Path

REQUEST_ID = re.compile(r'^[a-zA-Z0-9_-]{8,80}$')
MEDIA_NAME = re.compile(r'^[a-f0-9]{32}\.(?:png|jpg|jpeg|webp|mp4|gif)$')
INPUT_KEYS = ('initial_frame', 'end_frame', 'reference_images')


class DirectError(Exception):
    def __init__(self, code, status_code=400, detail=None):
        super().__init__(code)
        self.code = code
        self.status_code = status_code
        self.detail = detail


def _modules():
    """Desktop modules deployed next to the bridge (flow_provider, flow_contract, flow_batch, flow_automation)."""
    here = Path(__file__).resolve().parent
    # Deployed: copied next to recovery.py. In the repository: ../../desktop.
    for folder in (here, here.parent.parent / 'desktop'):
        if (folder / 'flow_provider.py').is_file() and str(folder) not in sys.path:
            sys.path.insert(0, str(folder))
    try:
        return importlib.import_module('flow_provider'), importlib.import_module('flow_contract')
    except ImportError as error:
        raise DirectError('flow_direct_not_installed', 503, str(error)) from None


def data_dir(root: Path) -> Path:
    path = root / 'flow-direct'
    (path / 'media').mkdir(parents=True, exist_ok=True)
    return path


def available() -> bool:
    try:
        provider, _ = _modules()
        return bool(provider.available())
    except DirectError:
        return False


def capabilities() -> dict:
    """Every model/mode/aspect/duration/resolution combination the verified contract accepts."""
    provider, contract = _modules()
    models = []
    for model in sorted(contract.IMAGES | contract.VIDEOS):
        image = model in contract.IMAGES
        modes = ['t2i'] if image else ['t2v', 'i2v', 'r2v']
        entry = {'model': model, 'kind': 'image' if image else 'video', 'modes': []}
        for mode in modes:
            sample = {'t2i': {}, 't2v': {}, 'i2v': {'initial_frame': 'x'}, 'r2v': {'reference_images': ['x']}}[mode]
            aspects = [a for a in ('16:9', '9:16', '1:1', '4:3', '3:4') if _valid(contract, {'model': model, 'aspect': a, 'mode': mode, **sample})]
            if not aspects:
                continue
            durations = [] if image else [d for d in range(1, 13) if _valid(contract, {'model': model, 'aspect': aspects[0], 'mode': mode, 'duration': d, **sample})]
            resolutions = [] if image else [r for r in ('360p', '720p', '1080p', '4k') if _valid(contract, {'model': model, 'aspect': aspects[0], 'mode': mode, 'resolution': r, **sample})]
            end_frame = mode == 'i2v' and _valid(contract, {'model': model, 'aspect': aspects[0], 'mode': mode, 'initial_frame': 'x', 'end_frame': 'y'})
            max_refs = 0
            if mode == 'r2v' or image:
                for n in range(1, 13):
                    refs = {'reference_images': [f'r{i}' for i in range(n)]}
                    if _valid(contract, {'model': model, 'aspect': aspects[0], 'mode': mode, **refs}):
                        max_refs = n
            entry['modes'].append({'mode': mode, 'aspects': aspects, 'durations': durations, 'resolutions': resolutions,
                                   'end_frame': bool(end_frame), 'max_references': max_refs})
        counts = [c for c in range(1, 5) if _valid(contract, {'model': model, 'aspect': entry['modes'][0]['aspects'][0], 'count': c,
                                                                **({'mode': 't2v'} if not image else {})})]
        entry['counts'] = counts
        models.append(entry)
    return {'available': bool(provider.available()), 'models': models,
            'downloads': {'image': ['2k', '4k'], 'video': ['1080p', '4k']},
            'source': 'desktop/flow_contract.py (verified against the own Flow account)'}


def _valid(contract, args) -> bool:
    try:
        contract.normalize(args)
        return True
    except (ValueError, StopIteration):
        return False


def _stage_references(root: Path, data: Path, args: dict) -> dict:
    """Replace bridge reference ids (ref_<sha256>) by provider media names after re-checking their bytes."""
    from flow_references import reference_paths
    staged = dict(args)
    for key in INPUT_KEYS:
        value = args.get(key)
        if value in (None, '', []):
            staged.pop(key, None)
            continue
        ids = value if isinstance(value, list) else [value]
        names = []
        for path in reference_paths(root, ids):
            name = path.stem[4:36] + path.suffix.lower()
            target = data / 'media' / name
            if not target.is_file() or target.stat().st_size != path.stat().st_size:
                temporary = target.with_suffix(target.suffix + '.tmp')
                shutil.copyfile(path, temporary)
                temporary.replace(target)
            names.append(name)
        staged[key] = names if key == 'reference_images' else names[0]
    return staged


def _clean(args) -> dict:
    if not isinstance(args, dict):
        raise DirectError('invalid_request')
    allowed = {'model', 'aspect', 'mode', 'duration', 'resolution', 'count', 'voice', 'prompt', 'request_id', 'cost',
               'source_request_id', *INPUT_KEYS}
    unknown = set(args) - allowed
    if unknown:
        raise DirectError('unsupported_field', detail=sorted(unknown))
    return args


async def quote(root: Path, args: dict) -> dict:
    provider, _ = _modules()
    data = data_dir(root)
    params = _stage_references(root, data, _clean(args))
    params.pop('prompt', None); params.pop('request_id', None); params.pop('cost', None)
    try:
        return await asyncio.to_thread(provider.quote, params, str(data))
    except ValueError as error:
        raise DirectError('flow_direct_rejected', 409, str(error)) from None


async def submit(root: Path, args: dict) -> dict:
    """Needs `request_id`, `prompt` (unless processing an existing result) and `cost` equal to a fresh quote."""
    provider, _ = _modules()
    args = _clean(args)
    if not isinstance(args.get('request_id'), str) or not REQUEST_ID.fullmatch(args['request_id']):
        raise DirectError('invalid_request_id')
    if 'cost' not in args:
        raise DirectError('quote_confirmation_required', 409, 'Consulta el importe y confírmalo antes de enviar.')
    data = data_dir(root)
    staged = _stage_references(root, data, args)
    try:
        return await asyncio.to_thread(provider.submit, str(data), staged)
    except ValueError as error:
        raise DirectError('flow_direct_rejected', 409, str(error)) from None
    except RuntimeError as error:
        raise DirectError('flow_direct_uncertain', 503, str(error)) from None


async def status(root: Path, request_id: str, recover: bool = False) -> dict:
    provider, _ = _modules()
    if not REQUEST_ID.fullmatch(request_id or ''):
        raise DirectError('invalid_request_id')
    data = str(data_dir(root))
    try:
        return await asyncio.to_thread(provider.recover if recover else provider.status, data, request_id)
    except ValueError as error:
        raise DirectError('flow_direct_not_found', 404, str(error)) from None


async def asset_options(source_request_id: str) -> dict:
    provider, _ = _modules()
    if not REQUEST_ID.fullmatch(source_request_id or ''):
        raise DirectError('invalid_request_id')
    try:
        return await asyncio.to_thread(provider.asset_options, source_request_id)
    except ValueError as error:
        raise DirectError('flow_direct_rejected', 409, str(error)) from None


def media_file(root: Path, name: str) -> Path:
    """Only completed results the provider copied into its media folder, by content-derived name."""
    if not MEDIA_NAME.fullmatch(name or ''):
        raise DirectError('invalid_media', 404)
    media = (data_dir(root) / 'media').resolve()
    path = (media / name).resolve()
    if path.parent != media or not path.is_file():
        raise DirectError('media_not_found', 404)
    return path
