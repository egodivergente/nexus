'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync(require('node:path').join(__dirname,'../ui/flow-assets.js'),'utf8');
const context=vm.createContext({escape:s=>String(s??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]))});
vm.runInContext(source.slice(source.indexOf('function flowAgentResult('),source.indexOf('let flowAvailabilityTimer')),context);
const render=job=>{context.job=job;return vm.runInContext('flowAgentResult(job)',context);};
const job={status:'COMPLETED',modality:'IMAGE',name:'<script>alert(1)</script>',outputs:['/media/'+'a'.repeat(32)+'.png']};
assert.match(render(job),/<img /);assert.match(render(job),/Guardar resultado/);assert.doesNotMatch(render(job),/<script>/);
assert.doesNotMatch(render({...job,status:'PROCESSING'}),/<img |Guardar resultado/);
assert.doesNotMatch(render({...job,outputs:['https://example.com/unverified.png']}),/<img |Guardar resultado/);
assert.doesNotMatch(render({...job,outputs:['javascript:alert(1)']}),/<img |Guardar resultado/);
assert.match(render({...job,modality:'VIDEO',outputs:['/media/'+'b'.repeat(32)+'.mp4']}),/<video /);
console.log('PASS: the agent displays completed local Flow results and preserves pending/unverified states.');
