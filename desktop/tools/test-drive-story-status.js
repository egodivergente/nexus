'use strict';
const assert=require('node:assert/strict');
const {narrativeSummary,editorial,conflictKind,conflictName,conflictFields}=require('../ui/drive-sync.js');
const complete={supported:true,enabled:true,state:'synced',conflicts:0,pendingDependencies:0};
assert.equal(narrativeSummary({state:'synced'}).text,'Guion y storyboard pausados');
assert.equal(narrativeSummary({state:'synced',storyEnabled:true}).text,'Guion pendiente de sincronizar');
assert.equal(narrativeSummary({state:'synced',storyEnabled:true,narrativeSync:complete}).text,'Guion compartido en Drive');
assert.match(narrativeSummary({storyEnabled:true,narrativeSync:complete}).detail,/completar su sincronización/);
assert.equal(narrativeSummary({storyEnabled:false,narrativeSync:complete}).text,'Guion y storyboard pausados');
assert.equal(narrativeSummary({storyEnabled:true,narrativeSync:{...complete,supported:false}}).tone,'warning');
assert.equal(narrativeSummary({storyEnabled:true,narrativeSync:{...complete,conflicts:2}}).text,'Guion con versiones para revisar');
assert.equal(narrativeSummary({storyEnabled:true,narrativeSync:{...complete,pendingDependencies:1}}).text,'Guion con vínculos pendientes');
assert.equal(narrativeSummary({storyEnabled:true,narrativeSync:{...complete,state:'error'}}).tone,'warning');
assert.equal(narrativeSummary({storyEnabled:true,narrativeSync:{...complete,state:'future-state'}}).tone,'neutral');
const text='La nota completa no se recorta al comparar sus versiones. '.repeat(4);
const wrapped={id:'block-private-id',projectId:'project-private-id',format:1,commonHash:'opaque-hash',payload:{text,narrativeState:'idea'}};
assert.equal(editorial(wrapped).text,text);
assert.equal(conflictKind('story:blocks:block-private-id'),'blocks');
assert.equal(conflictKind('assets:asset-private-id'),'assets');
assert.equal(conflictName({id:'shot-private-id',payload:{camera:'Cámara fija'}},id=>id==='shot-private-id'?'La mirada':null),'La mirada');
const fields=conflictFields(wrapped);
assert.deepEqual(fields.find(([label])=>label==='Texto'),['Texto',text]);
assert.ok(!JSON.stringify(fields).includes('private-id'));
assert.ok(!JSON.stringify(fields).includes('opaque-hash'));
const link=conflictFields({id:'link',payload:{assetId:'asset-private-id',targetId:'shot-private-id',role:'candidate',selected:true}},id=>({'asset-private-id':'Retrato de Mateo','shot-private-id':'La mirada'})[id]);
assert.ok(link.some(([name,value])=>name==='Archivo'&&value==='Retrato de Mateo'));
assert.ok(link.some(([name,value])=>name==='Destino'&&value==='La mirada'));
assert.ok(link.some(([name,value])=>name==='Material elegido'&&value==='Sí'));
const scope=conflictFields({payload:{scope:'scene',behavior:'replace',order:2,durationSec:4.5,role:'source'}});
assert.ok(scope.some(([name,value])=>name==='Alcance'&&value==='Escena'));
assert.ok(scope.some(([name,value])=>name==='Referencias'&&value==='Sustituye las referencias generales'));
assert.ok(scope.some(([name,value])=>name==='Posición'&&value==='3'));
assert.ok(scope.some(([name,value])=>name==='Duración orientativa'&&value==='4.5 s'));
assert.ok(scope.some(([name,value])=>name==='Uso del material'&&value==='Material de origen'));
console.log('PASS: honest narrative status, wrapped conflicts, related names and full story text');
